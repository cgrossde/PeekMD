//! Helper binary: regenerates the vendored syntect CSS files.
//! Run: cargo run --bin gen_syntect_css  (from src-tauri/)
//!
//! Input files (see assets/themes/README.md):
//!   assets/themes/GitHub-Light.tmTheme
//!   assets/themes/GitHub-Dark.tmTheme
//!
//! Output files:
//!   ../src/vendor/syntect-github-light.css
//!   ../src/vendor/syntect-github-dark.css

use std::io::BufReader;
use syntect::highlighting::ThemeSet;
use syntect::html::{css_for_theme_with_class_style, ClassStyle};

fn load_theme(path: &std::path::Path) -> syntect::highlighting::Theme {
    let file = std::fs::File::open(path)
        .unwrap_or_else(|e| panic!("failed to open {}: {}", path.display(), e));
    ThemeSet::load_from_reader(&mut BufReader::new(file))
        .unwrap_or_else(|e| panic!("failed to parse {}: {}", path.display(), e))
}

fn main() {
    let assets_dir = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("assets/themes");

    // GitHub's own official syntax themes (vendored — see assets/themes/README.md),
    // not syntect's bundled defaults. syntect's ThemeSet::load_defaults() has no
    // "GitHub Dark" theme; the previous stand-in (`base16-ocean.dark`) is an
    // unrelated blue/teal palette, not GitHub's actual dark syntax colors.
    let light_theme = load_theme(&assets_dir.join("GitHub-Light.tmTheme"));
    let dark_theme = load_theme(&assets_dir.join("GitHub-Dark.tmTheme"));

    let light_css = css_for_theme_with_class_style(&light_theme, ClassStyle::Spaced)
        .expect("failed to generate light CSS");
    let dark_css = css_for_theme_with_class_style(&dark_theme, ClassStyle::Spaced)
        .expect("failed to generate dark CSS");

    let light_wrapped = format!(
        "/* Generated by cargo run --bin gen_syntect_css. Do not edit. */\n\
         :root:not([data-theme=\"dark\"]) .markdown-body {{\n{}\n}}\n",
        light_css
    );
    let dark_wrapped = format!(
        "/* Generated by cargo run --bin gen_syntect_css. Do not edit. */\n\
         [data-theme=\"dark\"] .markdown-body {{\n{}\n}}\n",
        dark_css
    );

    let out_dir = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../src/vendor");
    std::fs::create_dir_all(&out_dir).expect("create vendor dir");

    let light_path = out_dir.join("syntect-github-light.css");
    let dark_path = out_dir.join("syntect-github-dark.css");

    std::fs::write(&light_path, &light_wrapped).expect("write light CSS");
    std::fs::write(&dark_path, &dark_wrapped).expect("write dark CSS");

    println!("Wrote {}", light_path.display());
    println!("Wrote {}", dark_path.display());
}
